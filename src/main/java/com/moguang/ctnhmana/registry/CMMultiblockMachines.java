    public static List<Component> addManaMachineTooltips(Lang[] langs, int consumption) {
        List<Component> list = new ArrayList<>();
        int y = 0;
        for (Lang lang : langs) {
            if (y != 3) list.add(lang.translate());
            if (y == 3) list.add(lang.translate(consumption));
            y += 1;
        }
        return list;
    }

